-- MySQL 8.0.16+。新建业务表设计稿，金额统一为人民币分，业务时间统一按 UTC 写入。
-- 商品和订单编号为租户内业务编号，由业务系统分配。外部编号由接入层识别和绑定。
-- 逻辑删除不释放业务编号。以下按父表先于子表排列。

CREATE TABLE goods_spu (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '商品主键',
    tenant_id VARCHAR(32) NOT NULL COMMENT '租户标识',
    spu_code VARCHAR(64) NOT NULL COMMENT '租户内稳定商品编码，创建后不可变',
    spu_name VARCHAR(256) NOT NULL COMMENT '对客商品名称',
    product_kind VARCHAR(24) NOT NULL COMMENT '商品形态：PACKAGE 套餐，VOUCHER 代金券，OTHER 其他已识别形态',
    category_id BIGINT DEFAULT NULL COMMENT '业务商品分类主键，未归类时为空',
    image_urls JSON DEFAULT NULL COMMENT '有序商品图片地址数组，首项为主图',
    applicable_shop_ids JSON DEFAULT NULL COMMENT '适用的本地门店ID字符串数组；空数组表示无适用门店，NULL表示范围待确认，不表示全部门店',
    review_state VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT '本次商品资料审核进度：DRAFT 草稿，PENDING 待审，APPROVED 通过，REJECTED 驳回',
    review_note VARCHAR(512) DEFAULT NULL COMMENT '最近一次业务审核意见',
    is_visible TINYINT NOT NULL DEFAULT 0 COMMENT '是否展示给顾客：0 隐藏，1 展示；独立于可售状态',
    is_on_sale TINYINT NOT NULL DEFAULT 0 COMMENT '业务是否开放购买：0 停售，1 可售；仍需校验门店、规格及库存规则',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建人ID，0表示系统',
    created_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '建档时间',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '最近更新人ID，0表示系统',
    updated_time DATETIME(3) DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最近更新时间',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 正常，1 已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_goods_spu_code (tenant_id, spu_code),
    UNIQUE KEY uk_goods_spu_tenant_id (tenant_id, id),
    KEY idx_goods_spu_catalog (tenant_id, deleted, is_visible, category_id),
    CONSTRAINT chk_goods_spu_kind CHECK (product_kind IN ('PACKAGE','VOUCHER','OTHER')),
    CONSTRAINT chk_goods_spu_review CHECK (review_state IN ('DRAFT','PENDING','APPROVED','REJECTED')),
    CONSTRAINT chk_goods_spu_flags CHECK (is_visible IN (0,1) AND is_on_sale IN (0,1) AND deleted IN (0,1)),
    CONSTRAINT chk_goods_spu_images CHECK (image_urls IS NULL OR JSON_TYPE(image_urls) = 'ARRAY'),
    CONSTRAINT chk_goods_spu_shops CHECK (applicable_shop_ids IS NULL OR JSON_TYPE(applicable_shop_ids) = 'ARRAY')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='商品目录：商品的业务定义、展示和销售范围';

CREATE TABLE goods_sku (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '销售规格主键',
    tenant_id VARCHAR(32) NOT NULL COMMENT '租户标识',
    spu_id BIGINT NOT NULL COMMENT '所属本地商品主键',
    sku_code VARCHAR(64) NOT NULL COMMENT '租户内稳定规格编码，创建后不可变',
    sku_name VARCHAR(256) NOT NULL COMMENT '可购买的规格名称',
    sale_price_cent BIGINT DEFAULT NULL COMMENT '当前销售单价，人民币分；NULL表示尚未定价，0表示免费',
    list_price_cent BIGINT DEFAULT NULL COMMENT '展示参考价，人民币分；未设置时为空',
    stock_mode VARCHAR(16) NOT NULL DEFAULT 'UNSET' COMMENT '库存规则：UNSET 待配置，UNLIMITED 不限量，LIMITED 限量',
    stock_limit BIGINT DEFAULT NULL COMMENT '该规格配置的销售总量上限；仅限量时有值，不表示实时可用库存',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建人ID，0表示系统',
    created_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '建档时间',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '最近更新人ID，0表示系统',
    updated_time DATETIME(3) DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最近更新时间',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 正常，1 已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_goods_sku_code (tenant_id, sku_code),
    UNIQUE KEY uk_goods_sku_tenant_id (tenant_id, id),
    KEY idx_goods_sku_spu (tenant_id, spu_id, deleted),
    CONSTRAINT fk_goods_sku_spu FOREIGN KEY (tenant_id, spu_id) REFERENCES goods_spu (tenant_id, id),
    CONSTRAINT chk_goods_sku_prices CHECK ((sale_price_cent IS NULL OR sale_price_cent >= 0) AND (list_price_cent IS NULL OR list_price_cent >= 0)),
    CONSTRAINT chk_goods_sku_stock CHECK ((stock_mode IN ('UNSET','UNLIMITED') AND stock_limit IS NULL) OR (stock_mode = 'LIMITED' AND stock_limit IS NOT NULL AND stock_limit >= 0)),
    CONSTRAINT chk_goods_sku_deleted CHECK (deleted IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='商品销售规格：当前报价和限量规则';

CREATE TABLE trade_order (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '交易订单主键',
    tenant_id VARCHAR(32) NOT NULL COMMENT '租户标识',
    order_no VARCHAR(64) NOT NULL COMMENT '租户内稳定业务订单号，推送及补查共用',
    order_kind VARCHAR(24) DEFAULT NULL COMMENT '业务交易形态，如团购 GROUP_BUY 或预付 PREPAY；未确认时为空',
    fulfillment_mode VARCHAR(24) DEFAULT NULL COMMENT '约定履约方式，如凭券使用 VOUCHER、到店自提 PICKUP 或预约 RESERVATION；未确认时为空',
    shop_id BIGINT DEFAULT NULL COMMENT '已确认的本地下单门店ID',
    buyer_id BIGINT DEFAULT NULL COMMENT '已确认的本地买家ID',
    order_state VARCHAR(20) DEFAULT NULL COMMENT '交易生命周期：CREATED 已创建，AWAITING_PAYMENT 待支付，CONFIRMED 已成立，CANCELLED 已取消，CLOSED 已关闭；未知为空',
    fulfillment_state VARCHAR(16) DEFAULT NULL COMMENT '履约结果：PENDING 待履约，PARTIAL 部分完成，FULFILLED 全部完成，EXPIRED 已过期；未知为空',
    refund_state VARCHAR(16) DEFAULT NULL COMMENT '最近已确认的退款处理状态：NONE 无退款，PROCESSING 处理中，SUCCEEDED 成功，FAILED 失败；未知为空',
    placed_time DATETIME(3) DEFAULT NULL COMMENT '业务下单时间，UTC；未知为空',
    paid_time DATETIME(3) DEFAULT NULL COMMENT '支付成功时间，UTC；未知为空',
    gross_amount_cent BIGINT DEFAULT NULL COMMENT '整单优惠前金额，人民币分；未知为空',
    merchant_discount_cent BIGINT DEFAULT NULL COMMENT '商家承担的优惠金额，人民币分；未知为空',
    paid_amount_cent BIGINT DEFAULT NULL COMMENT '买家实际支付金额，人民币分；未知为空，不扣减后续退款',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建人ID，0表示系统',
    created_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '订单记录首次写入时间',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '最近更新人ID，0表示系统',
    updated_time DATETIME(3) DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最近更新时间',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 正常，1 已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_trade_order_no (tenant_id, order_no),
    UNIQUE KEY uk_trade_order_tenant_id (tenant_id, id),
    KEY idx_trade_order_placed (tenant_id, placed_time),
    KEY idx_trade_order_buyer (tenant_id, buyer_id, placed_time),
    CONSTRAINT chk_trade_order_state CHECK (order_state IN ('CREATED','AWAITING_PAYMENT','CONFIRMED','CANCELLED','CLOSED')),
    CONSTRAINT chk_trade_order_fulfillment CHECK (fulfillment_state IN ('PENDING','PARTIAL','FULFILLED','EXPIRED')),
    CONSTRAINT chk_trade_order_refund CHECK (refund_state IN ('NONE','PROCESSING','SUCCEEDED','FAILED')),
    CONSTRAINT chk_trade_order_amount CHECK ((gross_amount_cent IS NULL OR gross_amount_cent >= 0) AND (merchant_discount_cent IS NULL OR merchant_discount_cent >= 0) AND (paid_amount_cent IS NULL OR paid_amount_cent >= 0)),
    CONSTRAINT chk_trade_order_deleted CHECK (deleted IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='交易订单：成交、履约、退款及支付事实';

CREATE TABLE trade_order_item (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '订单明细主键',
    tenant_id VARCHAR(32) NOT NULL COMMENT '租户标识',
    order_id BIGINT NOT NULL COMMENT '所属本地交易订单主键',
    line_no INT NOT NULL COMMENT '订单内稳定行号，从1开始；重复同步复用原行号',
    sku_id BIGINT DEFAULT NULL COMMENT '经确认的本地规格主键；目录未匹配时允许为空',
    product_name_snapshot VARCHAR(256) DEFAULT NULL COMMENT '购买时的商品名称，未知为空',
    sku_name_snapshot VARCHAR(256) DEFAULT NULL COMMENT '购买时的规格名称，未知为空',
    quantity BIGINT DEFAULT NULL COMMENT '该行购买数量，未知为空',
    unit_price_cent BIGINT DEFAULT NULL COMMENT '订单确认的商品单价，人民币分；未知为空',
    created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建人ID，0表示系统',
    created_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '明细首次写入时间',
    updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '最近更新人ID，0表示系统',
    updated_time DATETIME(3) DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最近更新时间',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 正常，1 已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_trade_order_item_line (tenant_id, order_id, line_no),
    KEY idx_trade_order_item_sku (tenant_id, sku_id),
    CONSTRAINT fk_trade_item_order FOREIGN KEY (tenant_id, order_id) REFERENCES trade_order (tenant_id, id),
    CONSTRAINT fk_trade_item_sku FOREIGN KEY (tenant_id, sku_id) REFERENCES goods_sku (tenant_id, id),
    CONSTRAINT chk_trade_item_values CHECK (line_no > 0 AND (quantity IS NULL OR quantity > 0) AND (unit_price_cent IS NULL OR unit_price_cent >= 0)),
    CONSTRAINT chk_trade_item_deleted CHECK (deleted IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='交易订单明细：购买时的商品、规格、数量和单价快照';
